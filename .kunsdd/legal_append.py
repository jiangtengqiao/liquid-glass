# 追加生成模板
def gen_terms(doc, terms):
    out = ['\n\n# 附：名词释义\n']
    for i, (t, d) in enumerate(terms, 1):
        out.append(f"**{t}**：{d}")
        out.append(f"在本语境下，{t} 的含义以本释义为准；如法律法规或行业惯例另有定义，从其定义。相关认定需结合具体场景，{d[:30]}……等情况均纳入本条理解范围。")
        out.append("")
    return out

def gen_faqs(doc, faqs):
    out = ['\n\n# 附：常见问题（FAQ）\n']
    for i, (q, a) in enumerate(faqs, 1):
        out.append(f"**问：{q}**")
        out.append(f"答：{a} 同时，如您对本问题有其他疑问或遇到新的情形，可通过文末联系方式（jiangtengqiao@qq.com）向我们咨询，我们将在合理期限内答复。")
        out.append("")
    return out

