    lines.append(f"# {doc['title']}")
    lines.append("")
    lines.append(f"**版本：{doc['ver']}**")
    lines.append(f"**生效日期：{doc['date']}**")
    lines.append(f"**更新日期：{doc['date']}**")
    lines.append("")
    lines.append("感谢您使用璃光 GlassSuite（以下简称\"本软件\"或\"我们\"）。请您在使用本软件前仔细阅读以下条款。")
    lines.append("")
    for title, points in doc['sections']:
        lines += expand(title, points)
    lines.append("（全文完）")
    lines.append("")
    return "\n".join(lines)

